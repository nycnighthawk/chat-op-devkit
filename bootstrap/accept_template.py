#!/usr/bin/env python3
"""Black-box conformance for a chatop build: replays the reference labs through its CLI.

    CHATOP=".venv/bin/chatop" python accept.py all          # or: lab1 .. lab5 / a lab name
    python accept.py --list

Needs only the Python stdlib and git. The app under test is any command that behaves like `chatop`
(env CHATOP, default "chatop"). Generated by scripts/build_bootstrap.py from labs/: do not edit by hand.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shlex
import subprocess
import sys
import tempfile
from pathlib import Path

DATA = json.loads("__DATA__")
ALIASES = {f"lab{i}": n for i, n in enumerate(DATA["order"], 1)}


class Fail(Exception):
    pass


class Lab:
    def __init__(self, cmd: list[str], work: Path) -> None:
        self.cmd, self.work, self.last, self.current = cmd, work, "", ""
        self.env = {**os.environ, "CHATOP_CLIPBOARD": "file", "PYTHONDONTWRITEBYTECODE": "1"}

    def git(self, *a: str) -> None:
        subprocess.run(["git", *a], cwd=self.work, check=True, capture_output=True)

    def chatop(self, *a: str) -> tuple[int, str]:
        p = subprocess.run([*self.cmd, "-C", str(self.work), *a], capture_output=True, text=True, env=self.env)
        return p.returncode, p.stdout + p.stderr

    def status(self) -> dict[str, object]:
        code, out = self.chatop("status", "--json")
        if code != 0:
            raise Fail(f"`status --json` exited {code}: {out.strip()[:300]}")
        try:
            data: dict[str, object] = json.loads(out)
            return data
        except json.JSONDecodeError as e:
            raise Fail(f"`status --json` is not JSON ({e}): {out[:200]!r}") from e

    def fill(self, text: str, st: dict[str, object]) -> str:
        chats = {c["issue"]: c for c in st.get("chats", []) if c.get("issue")}  # type: ignore[attr-defined]

        def lane(m: re.Match[str]) -> str:
            c = chats.get(m.group(2))
            if c is None:
                raise Fail(f"no chat is working on issue {m.group(2)} (placeholder {m.group(0)})")
            return str(c["id"] if m.group(1) == "CHAT" else c["turn"])

        return re.sub(r"@(CHAT|TURN):([\w-]+)@", lane, text).replace("@TURN@", str(st["turn"]))

    def init_repo(self) -> None:
        self.work.mkdir(parents=True, exist_ok=True)
        if not (self.work / ".git").exists():
            self.git("init", "-q", "-b", "main")
            for k, v in (("user.email", "lab@example.com"), ("user.name", "Lab"), ("commit.gpgsign", "false")):
                self.git("config", k, v)

    def run(self, name: str) -> None:
        """Replay one lab; replies are looked up in the lab that owns the running step (prerequisites too)."""
        outer, self.current = self.current, name
        self.init_repo()
        try:
            for n, raw in enumerate(DATA["labs"][name]["steps"].splitlines(), 1):
                line = raw.strip()
                if not line or line.startswith("#"):
                    continue
                verb, *rest = shlex.split(line)
                try:
                    self.step(verb, rest)
                except Fail as e:
                    raise Fail(f"{name} step {n}: {line}\n    {e}") from None
        finally:
            self.current = outer

    def step(self, verb: str, rest: list[str]) -> None:
        if verb == "chatop":
            code, self.last = self.chatop(*rest)
            if code != 0:
                raise Fail(f"exit {code}\n{self.last.strip()[-600:]}")
        elif verb in ("reply", "reply-rejected"):
            text = self.fill(DATA["replies"][self._lab_of_reply(rest[0])], self.status())
            with tempfile.NamedTemporaryFile("w", suffix=".md", delete=False) as fh:
                fh.write(text)
            code, self.last = self.chatop("apply", fh.name)
            if verb == "reply" and code != 0:
                raise Fail(f"reply {rest[0]} was rejected (exit {code})\n{self.last.strip()[-600:]}")
            if verb == "reply-rejected" and code == 0:
                raise Fail(f"reply {rest[0]} should have been rejected but exit was 0")
        elif verb == "seed":
            for rel, body in DATA["seeds"][rest[0]].items():
                dest = self.work / rel
                dest.parent.mkdir(parents=True, exist_ok=True)
                dest.write_text(body, encoding="utf-8")
            self.git("add", "-A")
            self.git("commit", "-q", "-m", rest[1].replace("\\n", "\n"))
        elif verb == "expect":
            st = self.status()
            for kv in rest:
                k, v = kv.split("=", 1)
                if str(st.get(k)) != v:
                    raise Fail(f"expected {k}={v}, got {st.get(k)}")
        elif verb == "expect-chat":
            st = self.status()
            chat = next((c for c in st.get("chats", []) if c["id"] == rest[0]), None)  # type: ignore[attr-defined]
            if chat is None:
                raise Fail(f"no chat {rest[0]}")
            for kv in rest[1:]:
                k, v = kv.split("=", 1)
                if str(chat.get(k)) != v:
                    raise Fail(f"chat {rest[0]}: expected {k}={v}, got {chat.get(k)}")
        elif verb == "expect-output":
            if " ".join(rest) not in self.last:
                raise Fail(f"expected the last output to contain {' '.join(rest)!r}\n{self.last.strip()[-400:]}")
        elif verb == "expect-file":
            if not (self.work / rest[0]).exists():
                raise Fail(f"expected file {rest[0]}")
        elif verb == "run-lab":
            self.run(rest[0])
        else:
            raise Fail(f"unknown verb {verb}")

    def _lab_of_reply(self, fname: str) -> str:
        return f"{self.current}/{fname}"


def run_one(cmd: list[str], name: str, keep: bool) -> bool:
    work = Path(tempfile.mkdtemp(prefix=f"accept-{name}-"))
    lab = Lab(cmd, work)
    try:
        lab.run(name)
    except Fail as e:
        print(f"FAIL {name}\n  {e}\n  workdir kept: {work}")
        return False
    print(f"ok   {name}")
    if not keep:
        subprocess.run(["rm", "-rf", str(work)])
    return True


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("lab", nargs="?", default="all")
    ap.add_argument("--list", action="store_true")
    ap.add_argument("--keep", action="store_true", help="keep work dirs of passing labs too")
    a = ap.parse_args()
    if a.list:
        for i, n in enumerate(DATA["order"], 1):
            print(f"lab{i}  {n}")
        return 0
    cmd = shlex.split(os.environ.get("CHATOP", "chatop"))
    names = DATA["order"] if a.lab == "all" else [ALIASES.get(a.lab, a.lab)]
    bad = [n for n in names if n not in DATA["labs"]]
    if bad:
        print(f"unknown lab {bad[0]}; try --list")
        return 2
    results = [run_one(cmd, n, a.keep) for n in names]
    print(f"\nchatop conformance: {sum(results)}/{len(results)} labs passed")
    return 0 if all(results) else 1


if __name__ == "__main__":
    sys.exit(main())
